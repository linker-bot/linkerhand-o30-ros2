def range_to_arc(range_vals, min_rad, max_rad, derict=None, skip=None, ndigits=3):
    """将 0-255 范围值线性映射为弧度值（统一核心函数）。

    range_vals / min_rad / max_rad 顺序一致、长度相同。
    derict: 可选方向列表，derict[i] == -1 时反向映射(0->max, 255->min)，否则正向(0->min, 255->max)。
    skip:   需跳过并置 0 的关节索引集合(如 L20/L21 的空关节)。
    ndigits: 结果保留的小数位数(默认 3)。
    """
    arc = [0.0] * len(min_rad)
    for i in range(len(min_rad)):
        if skip and i in skip:
            continue
        val = is_within_range(range_vals[i], 0, 255)
        if derict is not None and derict[i] == -1:
            arc[i] = round(scale_value(val, 0, 255, max_rad[i], min_rad[i]), ndigits)
        else:
            arc[i] = round(scale_value(val, 0, 255, min_rad[i], max_rad[i]), ndigits)
    return arc


